function quote(
  partial: Omit<QuoteRecord, "vatRate" | "activity"> & {
    activity?: QuoteRecord["activity"];
  },
): QuoteRecord {
  return {
    vatRate: 20,
    activity: partial.activity ?? [
      {
        id: `${partial.id}-created`,
        at: partial.createdAt,
        messageKey: "activity.quoteCreated",
        values: {
          name: owners.find((owner) => owner.id === partial.ownerId)?.name ?? "",
          id: partial.id,
        },
      },
    ],
    ...partial,
  };
}

