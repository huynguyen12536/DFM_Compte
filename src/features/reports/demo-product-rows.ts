export function mergeDemoProductRows(
  rows: ProductPerformanceRow[],
  options?: { includeDemo?: boolean },
): ProductPerformanceRow[] {
  if (options?.includeDemo === false) return rows;
  const existing = new Set(rows.map((row) => row.productId));
  const extras = DEMO_PRODUCT_ROWS.filter((row) => !existing.has(row.productId));
  return [...rows, ...extras].sort((left, right) => right.revenueCents - left.revenueCents);
}
