export function mergeDemoSalesRows(
  rows: SalesPerformanceRow[],
  options?: { includeDemo?: boolean },
): SalesPerformanceRow[] {
  if (options?.includeDemo === false) return rows;
  const existing = new Set(rows.map((row) => row.salespersonId));
  const extras = DEMO_SALES_ROWS.filter((row) => !existing.has(row.salespersonId));
  return [...rows, ...extras].sort((left, right) => right.revenueCents - left.revenueCents);
}
